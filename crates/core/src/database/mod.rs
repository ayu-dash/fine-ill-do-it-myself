use std::path::Path;

use crate::error::{Error, Result};
use crate::supervisor::Env;

/// Generate a minimal my.cnf for a fidim-managed datadir.
pub fn generate_mariadb_cnf(
    basedir: &str,
    datadir: &str,
    socket: &str,
    port: u16,
    log: &str,
    _user: &str,
    bind: &str,
) -> Result<String> {
    if basedir.is_empty() || datadir.is_empty() || socket.is_empty() || port == 0 {
        return Err(Error::Other("invalid mariadb settings".into()));
    }
    // Share fidim's pid file (`<run>/mariadb.pid`). Letting mariadbd write
    // `<socket>.pid` puts a second pid file in the run dir, and fidim treats
    // every `*.pid` there as a service, so `db.sock` showed up as a phantom
    // service next to `mariadb`.
    let pid_file = Path::new(socket).with_file_name("mariadb.pid");
    Ok(format!(
        r#"; generated by fidim (my.cnf)
[mysqld]
basedir = {basedir}
datadir = {datadir}
socket = {socket}
port = {port}
bind_address = {bind}
skip_name_resolve = 1
log_error = {log}
pid_file = {}
max_connections = 100
"#,
        pid_file.display()
    ))
}

/// Build the mariadbd start command from a resolved binary + config.
pub fn start_cmd(bin: &Path, basedir: &Path, cnf: &Path) -> Vec<String> {
    let mut cmd = Vec::new();
    if basedir.join("scripts/mariadb-install-db").is_file() {
        let mut library_paths = vec![basedir.join("lib")];
        let mysql_lib = basedir.join("lib/mysql");
        if mysql_lib.is_dir() {
            library_paths.push(mysql_lib);
        }
        if let Some(existing) = std::env::var_os("LD_LIBRARY_PATH") {
            library_paths.extend(std::env::split_paths(&existing));
        }
        if let Ok(library_path) = std::env::join_paths(library_paths) {
            cmd.extend([
                "/usr/bin/env".into(),
                format!("LD_LIBRARY_PATH={}", library_path.to_string_lossy()),
            ]);
        }
    }
    cmd.extend([
        bin.display().to_string(),
        // must be one word: `--defaults-file <path>` is silently ignored by mariadbd
        format!("--defaults-file={}", cnf.display()),
    ]);
    cmd
}

/// MariaDB convenience env required to run binaries from our own dir.
pub fn env_for_env(dir: &Path) -> [(std::ffi::OsString, std::ffi::OsString); 1] {
    [(
        std::ffi::OsString::from("MYSQL_HOME"),
        dir.as_os_str().to_os_string(),
    )]
}

pub fn datadir_missing(dir: &Path) -> bool {
    !dir.join("mysql").is_dir()
}

/// `mariadb` client to issue SQL: the managed copy first, then the system one.
pub fn mariadb_client(env: &Env) -> Option<std::path::PathBuf> {
    let managed = env.paths.bin().join("mariadb").join("mariadb");
    if managed.is_file() {
        return Some(managed);
    }
    crate::orchestrator::which_system("mariadb")
}

/// Command that creates `<name>` (utf8mb4) through the managed socket.
pub fn create_database_cmd(env: &Env, name: &str) -> Result<Vec<String>> {
    crate::project::validate_name(name)?;
    let client = mariadb_client(env).ok_or_else(|| {
        Error::Other(
            "mariadb client not found; run `fidim install mariadb` or install MariaDB".into(),
        )
    })?;
    let socket = env.paths.pids().join(crate::orchestrator::MARIADB_SOCKET);
    Ok(vec![
        client.display().to_string(),
        format!("--socket={}", socket.display()),
        "-uroot".into(),
        "-e".into(),
        format!(
            "CREATE DATABASE IF NOT EXISTS `{name}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;"
        ),
    ])
}

/// Create the database used by a new project (`fidim new --db`).
pub fn create_database<C: crate::proc::CommandRunner>(
    env: &Env,
    name: &str,
    runner: &C,
) -> Result<()> {
    let cmd = create_database_cmd(env, name)?;
    runner.run(&cmd, &[]).map(|_| ())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn env(t: &tempfile::TempDir) -> Env {
        let env = Env::new(t.path().join("app"), t.path().join("Sites"));
        env.ensure_dirs().unwrap();
        env
    }

    #[derive(Default)]
    struct FakeRunner {
        commands: std::sync::Arc<std::sync::Mutex<Vec<Vec<String>>>>,
    }

    impl crate::proc::CommandRunner for FakeRunner {
        fn run(&self, cmd: &[String], _envs: &[(String, String)]) -> Result<String> {
            self.commands.lock().unwrap().push(cmd.to_vec());
            Ok(String::new())
        }
    }

    #[test]
    fn create_database_targets_the_managed_socket_and_client() {
        let t = tempfile::tempdir().unwrap();
        let env = env(&t);
        let client = env.paths.bin().join("mariadb/mariadb");
        std::fs::create_dir_all(client.parent().unwrap()).unwrap();
        std::fs::write(&client, "").unwrap();

        let cmd = create_database_cmd(&env, "shop").unwrap();

        assert_eq!(cmd[0], client.display().to_string());
        let socket = env.paths.pids().join("db.sock");
        assert!(
            cmd.iter()
                .any(|a| a == &format!("--socket={}", socket.display())),
            "{cmd:?}"
        );
        assert!(
            cmd.iter()
                .any(|a| a.contains("CREATE DATABASE IF NOT EXISTS `shop`")),
            "{cmd:?}"
        );
        assert!(
            cmd.iter().any(|a| a.contains("utf8mb4")),
            "database must be utf8mb4: {cmd:?}"
        );
    }

    #[test]
    fn create_database_rejects_an_unsafe_name() {
        let t = tempfile::tempdir().unwrap();
        let env = env(&t);
        assert!(create_database_cmd(&env, "shop; DROP DATABASE x").is_err());
    }

    #[test]
    fn create_database_runs_the_client_once() {
        let t = tempfile::tempdir().unwrap();
        let env = env(&t);
        let client = env.paths.bin().join("mariadb/mariadb");
        std::fs::create_dir_all(client.parent().unwrap()).unwrap();
        std::fs::write(&client, "").unwrap();
        let runner = FakeRunner::default();

        create_database(&env, "shop", &runner).unwrap();

        assert_eq!(runner.commands.lock().unwrap().len(), 1);
    }

    #[test]
    fn cnf_contains_datadir_socket_port() {
        let out = generate_mariadb_cnf(
            "/d/mysql",
            "/d/data",
            "/d/run/db.sock",
            3306,
            "/d/logs/db.log",
            "u",
            "127.0.0.1",
        )
        .unwrap();
        assert!(out.contains("basedir = /d/mysql"));
        assert!(out.contains("datadir = /d/data"));
        assert!(out.contains("socket = /d/run/db.sock"));
        assert!(out.contains("port = 3306"));
        assert!(out.contains("bind_address = 127.0.0.1"));
    }

    #[test]
    fn cnf_writes_the_service_pid_file_not_one_beside_the_socket() {
        let out = generate_mariadb_cnf(
            "/d/mysql",
            "/d/data",
            "/d/run/db.sock",
            3306,
            "/d/logs/db.log",
            "u",
            "127.0.0.1",
        )
        .unwrap();
        assert!(
            out.contains("pid_file = /d/run/mariadb.pid"),
            "mariadbd must share fidim's pid file: {out}"
        );
        assert!(
            !out.contains("db.sock.pid"),
            "a pid file beside the socket becomes a phantom service: {out}"
        );
    }

    #[test]
    fn cnf_rejects_bad_settings() {
        assert!(generate_mariadb_cnf("", "/d", "/s", 3306, "/l", "u", "127.0.0.1").is_err());
        assert!(generate_mariadb_cnf("/b", "/d", "/s", 0, "/l", "u", "127.0.0.1").is_err());
    }

    #[test]
    fn start_cmd_references_defaults_file() {
        let t = tempfile::tempdir().unwrap();
        let cnf = Path::new("/d/etc/my.cnf");
        let cmd = start_cmd(Path::new("/usr/sbin/mariadbd"), t.path(), cnf);
        assert_eq!(cmd[0], "/usr/sbin/mariadbd");
        // `--defaults-file` only works as a single `--defaults-file=<path>` word;
        // splitting it makes mariadbd fall back to its compiled-in datadir.
        assert_eq!(cmd[1], format!("--defaults-file={}", cnf.display()));
        assert_eq!(cmd.len(), 2);
    }

    #[test]
    fn managed_start_command_sets_runtime_library_path() {
        let t = tempfile::tempdir().unwrap();
        std::fs::create_dir_all(t.path().join("scripts")).unwrap();
        std::fs::write(t.path().join("scripts/mariadb-install-db"), "").unwrap();
        let cmd = start_cmd(
            &t.path().join("bin/mariadbd"),
            t.path(),
            &t.path().join("etc/my.cnf"),
        );
        assert_eq!(cmd[0], "/usr/bin/env");
        assert!(cmd[1].starts_with("LD_LIBRARY_PATH="));
        assert_eq!(cmd[2], t.path().join("bin/mariadbd").display().to_string());
    }

    #[test]
    fn datadir_missing_when_mysql_subdir_absent() {
        let t = tempfile::tempdir().unwrap();
        assert!(datadir_missing(t.path()));
        std::fs::create_dir_all(t.path().join("mysql")).unwrap();
        assert!(!datadir_missing(t.path()));
    }

    #[test]
    fn env_point() {
        let t = tempfile::tempdir().unwrap();
        let p = t.path().to_path_buf();
        let env = env_for_env(&p);
        assert_eq!(env[0].0, std::ffi::OsString::from("MYSQL_HOME"));
    }
}
