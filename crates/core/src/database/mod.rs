use std::path::Path;

use crate::error::{Error, Result};

/// Generate a minimal my.cnf for a fidim-managed datadir.
pub fn generate_mariadb_cnf(
    datadir: &str,
    socket: &str,
    port: u16,
    log: &str,
    _user: &str,
    bind: &str,
) -> Result<String> {
    if datadir.is_empty() || socket.is_empty() || port == 0 {
        return Err(Error::Other("invalid mariadb settings".into()));
    }
    Ok(format!(
        r#"; generated by fidim (my.cnf)
[mysqld]
datadir = {datadir}
socket = {socket}
port = {port}
bind_address = {bind}
skip_name_resolve = 1
log_error = {log}
pid_file = {socket}.pid
max_connections = 100
"#
    ))
}

/// Build the mariadbd start command from a resolved binary + config.
pub fn start_cmd(bin: &Path, cnf: &Path) -> Vec<String> {
    vec![
        bin.display().to_string(),
        "--defaults-file".into(),
        cnf.display().to_string(),
    ]
}

/// MariaDB convenience env required to run binaries from our own dir.
pub fn env_for_env(dir: &Path) -> [(std::ffi::OsString, std::ffi::OsString); 1] {
    [(
        std::ffi::OsString::from("MYSQL_HOME"),
        dir.as_os_str().to_os_string(),
    )]
}

pub fn datadir_missing(dir: &Path) -> bool {
    !dir.join("mysql").is_dir()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn cnf_contains_datadir_socket_port() {
        let out = generate_mariadb_cnf(
            "/d/data",
            "/d/run/db.sock",
            3306,
            "/d/logs/db.log",
            "u",
            "127.0.0.1",
        )
        .unwrap();
        assert!(out.contains("datadir = /d/data"));
        assert!(out.contains("socket = /d/run/db.sock"));
        assert!(out.contains("port = 3306"));
        assert!(out.contains("bind_address = 127.0.0.1"));
    }

    #[test]
    fn cnf_rejects_bad_settings() {
        assert!(generate_mariadb_cnf("", "/s", 3306, "/l", "u", "127.0.0.1").is_err());
        assert!(generate_mariadb_cnf("/d", "/s", 0, "/l", "u", "127.0.0.1").is_err());
    }

    #[test]
    fn start_cmd_references_defaults_file() {
        let cmd = start_cmd(Path::new("/usr/bin/mariadbd"), Path::new("/d/etc/my.cnf"));
        assert_eq!(cmd[0], "/usr/bin/mariadbd");
        assert!(cmd[2].contains("my.cnf"));
    }

    #[test]
    fn datadir_missing_when_mysql_subdir_absent() {
        let t = tempfile::tempdir().unwrap();
        assert!(datadir_missing(t.path()));
        std::fs::create_dir_all(t.path().join("mysql")).unwrap();
        assert!(!datadir_missing(t.path()));
    }

    #[test]
    fn env_point() {
        let t = tempfile::tempdir().unwrap();
        let p = t.path().to_path_buf();
        let env = env_for_env(&p);
        assert_eq!(env[0].0, std::ffi::OsString::from("MYSQL_HOME"));
    }
}
