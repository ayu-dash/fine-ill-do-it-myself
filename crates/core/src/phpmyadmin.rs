//! phpMyAdmin integration: a managed install under
//! `runtimes/phpmyadmin/<version>/` that is exposed as a normal site
//! (`https://phpmyadmin.test`) through a symlink in the Sites folder. That way
//! vhost, certificate and hosts generation already work unchanged for every
//! web server.

use std::path::{Path, PathBuf};

use crate::error::{Error, Result};
use crate::supervisor::{Env, PortPlan};

/// Site folder / host label used for phpMyAdmin (`phpmyadmin.test`).
pub const SITE: &str = "phpmyadmin";

/// Installed phpMyAdmin tree: the highest version under `runtimes/phpmyadmin/`.
pub fn install_dir(env: &Env) -> Option<PathBuf> {
    let root = env.paths.runtimes().join(SITE);
    let mut versions: Vec<_> = std::fs::read_dir(&root)
        .ok()?
        .flatten()
        .filter(|e| e.path().is_dir())
        .collect();
    versions.sort_by_key(|e| version_key(&e.file_name()));
    versions.into_iter().rev().find_map(|e| {
        let dir = e.path();
        dir.join("index.php").is_file().then_some(dir)
    })
}

fn version_key(name: &std::ffi::OsStr) -> Vec<u64> {
    name.to_string_lossy()
        .split('.')
        .map(|p| p.parse::<u64>().unwrap_or(0))
        .collect()
}

/// Expose the installed tree as `<sites>/phpmyadmin` and (re)write
/// `config.inc.php` with the current MariaDB socket/port.
///
/// Returns the site path, or `None` when phpMyAdmin is not installed.
pub fn ensure_site(env: &Env, ports: &PortPlan) -> Result<Option<PathBuf>> {
    let Some(dir) = install_dir(env) else {
        return Ok(None);
    };
    let link = env.paths.sites().join(SITE);
    link_site(&link, &dir)?;

    let temp = dir.join("tmp");
    std::fs::create_dir_all(&temp)?;
    let secret = blowfish_secret(&env.paths.etc().join("phpmyadmin.blowfish"))?;
    let socket = env.paths.pids().join(crate::orchestrator::MARIADB_SOCKET);
    std::fs::write(
        dir.join("config.inc.php"),
        config_inc(ports, &socket, &temp, &secret),
    )?;
    Ok(Some(link))
}

/// Link `link` to `target`, replacing only links fidim created itself. A real
/// directory (a user project with the same name) is never touched.
fn link_site(link: &Path, target: &Path) -> Result<()> {
    match std::fs::symlink_metadata(link) {
        Ok(meta) if meta.file_type().is_symlink() => {
            if std::fs::read_link(link).ok().as_deref() == Some(target) {
                return Ok(());
            }
            std::fs::remove_file(link)?;
        }
        Ok(_) => {
            return Err(Error::Other(format!(
                "{} already exists and is not managed by fidim; refusing to replace it",
                link.display()
            )))
        }
        Err(_) => {}
    }
    if let Some(parent) = link.parent() {
        std::fs::create_dir_all(parent)?;
    }
    #[cfg(unix)]
    {
        std::os::unix::fs::symlink(target, link)?;
        Ok(())
    }
    #[cfg(not(unix))]
    {
        Err(Error::Other(
            "phpMyAdmin needs a symlink, which is only supported on unix".into(),
        ))
    }
}

fn blowfish_secret(path: &Path) -> Result<String> {
    if let Ok(existing) = std::fs::read_to_string(path) {
        let existing = existing.trim();
        if existing.len() >= 32 {
            return Ok(existing.to_string());
        }
    }
    use std::io::Read;
    let mut bytes = [0u8; 16];
    std::fs::File::open("/dev/urandom")?.read_exact(&mut bytes)?;
    let secret: String = bytes.iter().map(|b| format!("{b:02x}")).collect();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, &secret)?;
    Ok(secret)
}

/// Render `config.inc.php` for a fidim-managed MariaDB.
pub fn config_inc(ports: &PortPlan, socket: &Path, temp: &Path, secret: &str) -> String {
    let php_path = |p: &Path| {
        p.display()
            .to_string()
            .replace('\\', "\\\\")
            .replace('\'', "\\'")
    };
    format!(
        r#"<?php
// generated by fidim - do not edit
$cfg['blowfish_secret'] = '{secret}';
$i = 1;
$cfg['Servers'][$i]['auth_type'] = 'cookie';
$cfg['Servers'][$i]['host'] = 'localhost';
$cfg['Servers'][$i]['socket'] = '{}';
$cfg['Servers'][$i]['port'] = '{}';
$cfg['Servers'][$i]['user'] = 'root';
$cfg['Servers'][$i]['AllowNoPassword'] = true;
$cfg['Servers'][$i]['compress'] = false;
$cfg['TempDir'] = '{}';
$cfg['UploadDir'] = '';
$cfg['SaveDir'] = '';
"#,
        php_path(socket),
        ports.mariadb,
        php_path(temp)
    )
}

/// The browser URL for the phpMyAdmin site on the selected web server.
pub fn url(env: &Env, ports: &PortPlan) -> String {
    let web = crate::orchestrator::web_server(env);
    let (_, https) = ports.web_ports(&web);
    format!("https://{SITE}.test:{https}")
}

#[cfg(test)]
mod tests {
    use super::*;

    fn env() -> (Env, tempfile::TempDir) {
        let t = tempfile::tempdir().unwrap();
        let env = Env::new(t.path().join("app"), t.path().join("Sites"));
        env.ensure_dirs().unwrap();
        (env, t)
    }

    fn fake_install(env: &Env, version: &str) -> PathBuf {
        let dir = env.paths.runtimes().join("phpmyadmin").join(version);
        std::fs::create_dir_all(&dir).unwrap();
        std::fs::write(dir.join("index.php"), "<?php").unwrap();
        dir
    }

    #[test]
    fn install_dir_prefers_the_highest_version() {
        let (env, _t) = env();
        fake_install(&env, "5.2.2");
        let newest = fake_install(&env, "5.2.10");

        assert_eq!(
            install_dir(&env).map(|p| p.canonicalize().unwrap()),
            Some(newest.canonicalize().unwrap())
        );
    }

    #[test]
    fn ensure_site_is_a_noop_without_an_install() {
        let (env, _t) = env();

        assert_eq!(ensure_site(&env, &PortPlan::default()).unwrap(), None);
        assert!(!env.paths.sites().join(SITE).exists());
    }

    #[test]
    fn ensure_site_links_the_tree_and_writes_a_config() {
        let (env, _t) = env();
        let dir = fake_install(&env, "5.2.3");
        let ports = PortPlan {
            mariadb: 3307,
            ..PortPlan::default()
        };

        let link = ensure_site(&env, &ports).unwrap().unwrap();

        assert_eq!(link, env.paths.sites().join(SITE));
        assert_eq!(std::fs::read_link(&link).unwrap(), dir);
        assert!(dir.join("tmp").is_dir(), "phpMyAdmin needs a temp dir");

        let cfg = std::fs::read_to_string(dir.join("config.inc.php")).unwrap();
        let socket = env.paths.pids().join("db.sock");
        assert!(cfg.contains(&socket.display().to_string()), "{cfg}");
        assert!(cfg.contains("'cookie'"), "{cfg}");
        assert!(cfg.contains("AllowNoPassword"), "{cfg}");
        assert!(
            cfg.contains(&format!("['port'] = '{}'", ports.mariadb)),
            "{cfg}"
        );
        assert!(cfg.contains("blowfish_secret"), "{cfg}");
    }

    #[test]
    fn ensure_site_never_replaces_a_real_project_directory() {
        let (env, _t) = env();
        fake_install(&env, "5.2.3");
        let real = env.paths.sites().join(SITE);
        std::fs::create_dir_all(&real).unwrap();
        std::fs::write(real.join("index.html"), "mine").unwrap();

        let err = ensure_site(&env, &PortPlan::default()).unwrap_err();

        assert!(err.to_string().contains("refusing"), "{err}");
        assert_eq!(
            std::fs::read_to_string(real.join("index.html")).unwrap(),
            "mine"
        );
    }

    #[test]
    fn ensure_site_shows_up_as_a_project() {
        let (env, _t) = env();
        fake_install(&env, "5.2.3");

        ensure_site(&env, &PortPlan::default()).unwrap();

        assert!(crate::list_projects(&env).contains(&SITE.to_string()));
    }
}
