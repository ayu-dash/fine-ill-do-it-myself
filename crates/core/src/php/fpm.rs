use crate::error::{Error, Result};
use crate::supervisor::PortPlan;

/// Generate a php-fpm pool config for a static-php fpm binary.
pub fn generate_fpm_conf(
    listen: u16,
    pid_file: &str,
    log_path: &str,
    slowlog: &str,
) -> Result<String> {
    if listen == 0 {
        return Err(Error::Other("invalid fpm port 0".into()));
    }
    Ok(format!(
        r#"; generated by fidim
[global]
pid = {pid_file}
error_log = {log_path}
daemonize = no

[www]
listen = 127.0.0.1:{listen}
pm = dynamic
pm.max_children = 10
pm.start_servers = 2
pm.min_spare_servers = 1
pm.max_spare_servers = 4
catch_workers_output = yes
slowlog = {slowlog}
request_slowlog_timeout = 5s
php_admin_value[error_reporting] = E_ALL
php_admin_flag[display_errors] = on
"#
    ))
}

/// Port assignment for an fpm instance; base port per PHP minor version so
/// multiple versions can run simultaneously (8.1 -> 9001, 8.4 -> 9004...).
pub fn fpm_port_for(version: &str, base: u16, plan: &PortPlan) -> u16 {
    let _ = plan;
    let minor: u16 = version
        .split('.')
        .nth(1)
        .and_then(|m| m.parse().ok())
        .unwrap_or(0);
    base + minor
}

/// Write the global php.ini used by every static-php binary.
pub fn generate_php_ini(_enabled: &[&str]) -> String {
    r#"; PHP configuration generated by fidim
[PHP]
memory_limit = 512M
post_max_size = 100M
upload_max_filesize = 100M
max_execution_time = 300
max_input_time = 300
date.timezone = UTC
display_errors = On
display_startup_errors = On
log_errors = On
error_reporting = E_ALL
default_charset = "UTF-8"

[Date]
date.timezone = UTC
"#
    .to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fpm_conf_has_listen_and_pid() {
        let out = generate_fpm_conf(9004, "/p/pid", "/l/log", "/l/slow").unwrap();
        assert!(out.contains("listen = 127.0.0.1:9004"));
        assert!(out.contains("pid = /p/pid"));
    }

    #[test]
    fn fpm_conf_rejects_zero_port() {
        assert!(generate_fpm_conf(0, "/p", "/l", "/s").is_err());
    }

    #[test]
    fn port_offsets_by_minor_version() {
        let plan = PortPlan::default();
        assert_eq!(fpm_port_for("8.4", 9000, &plan), 9004);
        assert_eq!(fpm_port_for("8.1", 9000, &plan), 9001);
        // malformed versions fall back to base port
        assert_eq!(fpm_port_for("x", 9000, &plan), 9000);
    }
}
