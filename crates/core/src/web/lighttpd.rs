//! lighttpd config generation: one main conf plus per-project includes with
//! fastcgi proxy to php-fpm. TLS needs a combined PEM (crt+key) file per
//! project; the generator assembles it from the local CA leaf certs.
use crate::error::{Error, Result};

/// Main lighttpd.conf: modules, bind port, pid/log, and one include per project.
pub fn generate_lighttpd_conf(
    includes: &[String],
    http_port: u16,
    https_port: u16,
    pid: &str,
    error_log: &str,
    access_log: &str,
    docroot: &str,
) -> Result<String> {
    if http_port == 0 || https_port == 0 {
        return Err(Error::Other("port must not be 0".into()));
    }
    let inc = includes
        .iter()
        .map(|i| format!("include \"{i}\""))
        .collect::<Vec<_>>()
        .join("\n");
    Ok(format!(
        r#"# generated by fidim - do not edit
server.modules = ( "mod_accesslog", "mod_setenv", "mod_fastcgi", "mod_openssl", "mod_proxy", "mod_rewrite")
server.document-root = "{docroot}"
server.port = {http_port}
server.bind = "127.0.0.1"
server.pid-file = "{pid}"
server.errorlog = "{error_log}"
accesslog.filename = "{access_log}"
setenv.add-response-header = ( "X-Powered-By" => "fine-ill-do-it-myself" )
{inc}
"#
    ))
}

/// Per-project include: host-based vhost for HTTP. TLS lives in the shared
/// `_ssl.conf` socket block so every site can select its own certificate.
pub fn lighttpd_site_conf(site: &crate::site::Site, fpm_port: u16) -> Result<String> {
    let project = &site.name;
    if project.is_empty() {
        return Err(Error::Other("project name must not be empty".into()));
    }
    let docroot = site.docroot_str();
    let body = if let Some(port) = site.proxy {
        format!(
            "\tproxy.server = ( \"\" => ( ( \"host\" => \"127.0.0.1\", \"port\" => {port} ) ) )\n"
        )
    } else {
        let fcgi = format!(
            "\t\tfastcgi.server = ( \".php\" => ( ( \"host\" => \"127.0.0.1\", \"port\" => {fpm_port}, \"check-local\" => \"disable\" ) ) )\n"
        );
        // Same split as nginx: frameworks fall back to their front controller,
        // flat projects keep a 404 for paths that do not exist.
        let rewrite = if site.is_framework() {
            "\turl.rewrite-if-not-file = ( \"^/(.*)$\" => \"/index.php\" )\n"
        } else {
            ""
        };
        format!(
            "\tserver.document-root = \"{docroot}\"\n\tserver.indexfiles = ( \"index.php\", \"index.html\" )\n{rewrite}{fcgi}"
        )
    };
    Ok(format!(
        r#"$HTTP["host"] == "{project}.test" {{
{body}}}
"#
    ))
}

/// One TLS listener for every site. Lighttpd selects the certificate by SNI
/// through `ssl.pemfile` inside `$HTTP["host"]`, so all per-site PEMs must be
/// listed here; the first one is the fallback for unknown hostnames.
pub fn ssl_socket_conf(
    https_port: u16,
    default_pem: &std::path::Path,
    pems: &[(String, std::path::PathBuf)],
) -> String {
    let mut out = format!(
        "$SERVER[\"socket\"] == \":{https_port}\" {{\n\tssl.engine = \"enable\"\n\tssl.pemfile = \"{}\"\n",
        default_pem.display()
    );
    for (name, pem) in pems {
        out.push_str(&format!(
            "\t$HTTP[\"host\"] == \"{name}.test\" {{ ssl.pemfile = \"{}\" }}\n",
            pem.display()
        ));
    }
    out.push_str("}\n");
    out
}

/// Write lighttpd.conf + per-project includes under `etc/lighttpd`, building
/// combined PEMs (crt + key) from the local certs when both exist.
#[allow(clippy::too_many_arguments)]
pub fn regenerate(
    etc: &std::path::Path,
    default_root: &std::path::Path,
    pid: &str,
    error_log: &str,
    access_log: &str,
    sites: &[crate::site::Site],
    fpm_port: u16,
    http_port: u16,
    https_port: u16,
    certs_dir: Option<&str>,
) -> Result<()> {
    let conf_dir = etc.join("lighttpd");
    let sites_dir = conf_dir.join("sites");
    // The fallback document root lives in the data root, never in the user's
    // Sites folder (otherwise it shows up as a `_default.test` project).
    std::fs::create_dir_all(default_root)?;
    let default_docroot = default_root.display().to_string();
    let certs_out = conf_dir.join("certs");
    std::fs::create_dir_all(&sites_dir)?;
    if let Ok(rd) = std::fs::read_dir(&sites_dir) {
        for e in rd.flatten() {
            let _ = std::fs::remove_file(e.path());
        }
    }
    let mut includes = Vec::new();
    let mut pems: Vec<(String, std::path::PathBuf)> = Vec::new();
    for site in sites {
        let p = &site.name;
        let pem = certs_dir.and_then(|d| {
            let crt = std::path::Path::new(d).join(format!("{p}.crt"));
            let key = std::path::Path::new(d).join(format!("{p}.key"));
            (crt.exists() && key.exists()).then(|| {
                let pem_path = certs_out.join(format!("{p}.pem"));
                std::fs::create_dir_all(pem_path.parent().unwrap()).ok();
                let mut combined = String::new();
                combined.push_str(&std::fs::read_to_string(&crt).unwrap_or_default());
                combined.push_str(&std::fs::read_to_string(&key).unwrap_or_default());
                std::fs::write(&pem_path, combined).ok();
                pem_path
            })
        });
        let body = lighttpd_site_conf(site, fpm_port)?;
        std::fs::write(sites_dir.join(format!("{p}.conf")), body)?;
        includes.push(format!("{}/{}.conf", sites_dir.display(), p));
        if let Some(pem) = pem {
            pems.push((p.clone(), pem));
        }
    }
    // One TLS socket shared by every project; SNI picks the matching pem.
    let ssl_path = sites_dir.join("_ssl.conf");
    if let Some((_, default_pem)) = pems.first() {
        std::fs::write(&ssl_path, ssl_socket_conf(https_port, default_pem, &pems))?;
        includes.insert(0, format!("{}/_ssl.conf", sites_dir.display()));
    } else {
        let _ = std::fs::remove_file(&ssl_path);
    }
    let conf = generate_lighttpd_conf(
        &includes,
        http_port,
        https_port,
        pid,
        error_log,
        access_log,
        &default_docroot,
    )?;
    std::fs::write(conf_dir.join("lighttpd.conf"), conf)
        .map_err(|e| Error::Other(format!("write lighttpd.conf: {e}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn main_conf_binds_and_includes_projects() {
        let c = generate_lighttpd_conf(
            &["/etc/lighttpd/sites/a.conf".to_string()],
            8080,
            8443,
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            "/Sites",
        )
        .unwrap();
        assert!(c.contains("server.port = 8080"));
        assert!(c.contains("include \"/etc/lighttpd/sites/a.conf\""));
        assert!(c.contains("server.bind = \"127.0.0.1\""));
    }

    #[test]
    fn main_conf_omits_openssl_when_tls_is_not_configured() {
        let t = tempfile::tempdir().unwrap();
        let etc = t.path().join("etc");

        regenerate(
            &etc,
            &t.path().join("dashboard"),
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            &[],
            9004,
            8080,
            8443,
            None,
        )
        .unwrap();

        let conf = std::fs::read_to_string(etc.join("lighttpd/lighttpd.conf")).unwrap();
        assert!(
            !conf.contains("mod_openssl"),
            "openssl must not load without a TLS socket\n{conf}"
        );
    }

    #[test]
    fn site_conf_has_fastcgi_and_leaves_tls_to_the_shared_socket() {
        let c = lighttpd_site_conf(&site("blog", "/Sites/blog"), 9004).unwrap();
        assert!(c.contains("server.document-root = \"/Sites/blog\""));
        assert!(c.contains("\"port\" => 9004"));
        assert!(c.contains("\"check-local\" => \"disable\""));
        assert!(!c.contains("ssl"), "TLS lives in _ssl.conf, not the vhost");
    }

    #[test]
    fn ssl_socket_lists_every_site_certificate_and_a_default() {
        let pems = vec![
            ("blog".to_string(), std::path::PathBuf::from("/c/blog.pem")),
            ("shop".to_string(), std::path::PathBuf::from("/c/shop.pem")),
        ];

        let c = ssl_socket_conf(8443, std::path::Path::new("/c/blog.pem"), &pems);

        assert!(c.contains("$SERVER[\"socket\"] == \":8443\""), "{c}");
        assert!(c.contains("ssl.engine = \"enable\""), "{c}");
        assert!(c.contains("$HTTP[\"host\"] == \"blog.test\" { ssl.pemfile = \"/c/blog.pem\" }"));
        assert!(c.contains("$HTTP[\"host\"] == \"shop.test\" { ssl.pemfile = \"/c/shop.pem\" }"));
    }

    #[test]
    fn site_conf_uses_the_site_docroot() {
        let c = lighttpd_site_conf(&site("shop", "/Sites/shop/public"), 9004).unwrap();

        assert!(
            c.contains("server.document-root = \"/Sites/shop/public\""),
            "{c}"
        );
    }

    #[test]
    fn framework_site_rewrites_missing_paths_to_index_php() {
        let t = tempfile::tempdir().unwrap();
        let sites = t.path().join("Sites");
        std::fs::create_dir_all(sites.join("shop/public")).unwrap();
        std::fs::write(sites.join("shop/public/index.php"), "<?php").unwrap();
        let site = crate::site::Site::detect("shop", &sites);

        let c = lighttpd_site_conf(&site, 9004).unwrap();

        assert!(
            c.contains("url.rewrite-if-not-file = ( \"^/(.*)$\" => \"/index.php\" )"),
            "framework routes must reach index.php\n{c}"
        );
    }

    #[test]
    fn flat_site_does_not_rewrite_missing_paths() {
        let t = tempfile::tempdir().unwrap();
        let sites = t.path().join("Sites");
        std::fs::create_dir_all(sites.join("blog")).unwrap();
        let site = crate::site::Site::detect("blog", &sites);

        let c = lighttpd_site_conf(&site, 9004).unwrap();

        assert!(!c.contains("url.rewrite"), "{c}");
    }

    #[test]
    fn main_conf_loads_the_rewrite_module() {
        let c = generate_lighttpd_conf(
            &[],
            8080,
            8443,
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            "/Sites",
        )
        .unwrap();

        assert!(c.contains("\"mod_rewrite\""), "{c}");
    }

    #[test]
    fn proxy_site_uses_a_proxy_block_instead_of_a_document_root() {
        let mut site = site("app", "/Sites/app");
        site.proxy = Some(3000);

        let c = lighttpd_site_conf(&site, 9004).unwrap();

        assert!(c.contains("proxy.server"), "{c}");
        assert!(c.contains("\"port\" => 3000"), "{c}");
        assert!(!c.contains("server.document-root = \"/Sites/app\""), "{c}");
    }

    #[test]
    fn regenerate_keeps_the_fallback_site_out_of_the_sites_folder() {
        let t = tempfile::tempdir().unwrap();
        let etc = t.path().join("etc");
        let sites = t.path().join("Sites");
        std::fs::create_dir_all(&sites).unwrap();
        let default_root = t.path().join("lighttpd/default");

        regenerate(
            &etc,
            &default_root,
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            &[site("blog", "/Sites/blog")],
            9004,
            8080,
            8443,
            None,
        )
        .unwrap();

        assert!(
            !sites.join("_default").exists(),
            "the sites folder must stay project-only"
        );
        assert!(default_root.is_dir(), "fallback document root missing");
        let conf = std::fs::read_to_string(etc.join("lighttpd/lighttpd.conf")).unwrap();
        assert!(
            conf.contains(&default_root.display().to_string()),
            "fallback docroot must be inside the data root\n{conf}"
        );
    }

    #[test]
    fn regenerate_issues_one_certificate_per_site_for_sni() {
        let t = tempfile::tempdir().unwrap();
        let etc = t.path().join("etc");
        let certs = etc.join("certs");
        std::fs::create_dir_all(&certs).unwrap();
        for p in ["blog", "shop"] {
            std::fs::write(certs.join(format!("{p}.crt")), "CERT").unwrap();
            std::fs::write(certs.join(format!("{p}.key")), "KEY").unwrap();
        }

        regenerate(
            &etc,
            &t.path().join("lighttpd/default"),
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            &[site("blog", "/Sites/blog"), site("shop", "/Sites/shop")],
            9004,
            8080,
            8443,
            Some(certs.display().to_string().as_str()),
        )
        .unwrap();

        for p in ["blog", "shop"] {
            assert!(
                etc.join(format!("lighttpd/certs/{p}.pem")).exists(),
                "{p} must get its own pem"
            );
        }
        let ssl = std::fs::read_to_string(etc.join("lighttpd/sites/_ssl.conf")).unwrap();
        assert!(ssl.contains("$SERVER[\"socket\"] == \":8443\""), "{ssl}");
        assert!(
            ssl.contains("$HTTP[\"host\"] == \"blog.test\" { ssl.pemfile = \"")
                && ssl.contains("blog.pem"),
            "{ssl}"
        );
        assert!(
            ssl.contains("$HTTP[\"host\"] == \"shop.test\" { ssl.pemfile = \"")
                && ssl.contains("shop.pem"),
            "{ssl}"
        );
    }

    #[test]
    fn regenerate_builds_pem_and_clears_stale() {
        let t = tempfile::tempdir().unwrap();
        let etc = t.path().join("etc");
        let certs = etc.join("certs");
        std::fs::create_dir_all(&certs).unwrap();
        std::fs::write(certs.join("blog.crt"), "CERT").unwrap();
        std::fs::write(certs.join("blog.key"), "KEY").unwrap();
        let sites_dir = etc.join("lighttpd/sites");
        std::fs::create_dir_all(&sites_dir).unwrap();
        std::fs::write(sites_dir.join("old.conf"), "x").unwrap();
        regenerate(
            &etc,
            &t.path().join("lighttpd/default"),
            "/run/lighttpd.pid",
            "/logs/error.log",
            "/logs/access.log",
            &[site("blog", "/Sites/blog")],
            9004,
            8080,
            8443,
            Some(certs.display().to_string().as_str()),
        )
        .unwrap();
        let pem = std::fs::read_to_string(etc.join("lighttpd/certs/blog.pem")).unwrap();
        assert!(
            pem.contains("CERT") && pem.contains("KEY"),
            "crt+key combined"
        );
        let conf = std::fs::read_to_string(etc.join("lighttpd/lighttpd.conf")).unwrap();
        assert!(conf.contains("blog.conf"));
        assert!(!std::fs::exists(sites_dir.join("old.conf")).unwrap());
    }

    fn site(name: &str, docroot: &str) -> crate::site::Site {
        crate::site::Site {
            name: name.to_string(),
            docroot: std::path::PathBuf::from(docroot),
            proxy: None,
        }
    }
}
