//! nginx config generation: one main nginx.conf (daemon off for detached
//! supervision) plus one server block include per project.
use crate::error::{Error, Result};

/// Main nginx.conf: events, http block, includes for each project.
pub fn generate_nginx_conf(
    includes: &[String],
    pid: &str,
    error_log: &str,
    mime_types: Option<&str>,
) -> Result<String> {
    let mut http = String::from(
        "http {\n    default_type application/octet-stream;\n    sendfile on;\n    index index.php index.html;\n",
    );
    if let Some(mime) = mime_types {
        http.push_str(&format!("    include {mime};\n"));
    }
    for inc in includes {
        http.push_str(&format!("    include {inc};\n"));
    }
    http.push_str("}\n");
    Ok(format!(
        r#"# generated by fidim - do not edit
daemon off;
worker_processes 1;
pid {pid};
error_log {error_log};
events {{
    worker_connections 256;
}}
{http}"#
    ))
}

/// Server block for one project: HTTP listener plus TLS listener when cert
/// files are supplied. PHP goes to the fastcgi pass on `fpm_port`.
pub fn nginx_server_conf(
    project: &str,
    sites_root: &str,
    fpm_port: u16,
    http_port: u16,
    https_port: u16,
    cert: Option<(&std::path::Path, &std::path::Path)>,
) -> Result<String> {
    if project.is_empty() {
        return Err(Error::Other("project name must not be empty".into()));
    }
    let docroot = format!("{sites_root}/{project}");
    let php_location = format!(
        r#"    location ~ \.php$ {{
        fastcgi_pass 127.0.0.1:{fpm_port};
        include fastcgi_params;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_param SCRIPT_NAME $fastcgi_script_name;
    }}
"#
    );
    let mut out = format!(
        r#"server {{
    listen {http_port};
    server_name {project}.test;
    root {docroot};
    location / {{
        try_files $uri $uri/ =404;
    }}
{php_location}}}
"#
    );
    if let Some((crt, key)) = cert {
        let crt = crt.display();
        let key = key.display();
        out.push_str(&format!(
            r#"server {{
    listen {https_port} ssl;
    server_name {project}.test;
    root {docroot};
    ssl_certificate {crt};
    ssl_certificate_key {key};
    location / {{
        try_files $uri $uri/ =404;
    }}
{php_location}}}
"#
        ));
    }
    Ok(out)
}

/// Write nginx.conf + per-project includes under `etc/nginx`.
#[allow(clippy::too_many_arguments)]
pub fn regenerate(
    etc: &std::path::Path,
    pid: &str,
    error_log: &str,
    sites_root: &str,
    projects: &[String],
    fpm_port: u16,
    http_port: u16,
    https_port: u16,
    certs_dir: Option<&str>,
) -> Result<()> {
    let conf_dir = etc.join("nginx");
    let sites_dir = conf_dir.join("sites");
    std::fs::create_dir_all(&sites_dir)?;
    if let Ok(rd) = std::fs::read_dir(&sites_dir) {
        for e in rd.flatten() {
            let _ = std::fs::remove_file(e.path());
        }
    }
    let mut includes = Vec::new();
    for p in projects {
        let cert = certs_dir.map(|d| {
            (
                std::path::Path::new(d).join(format!("{p}.crt")),
                std::path::Path::new(d).join(format!("{p}.key")),
            )
        });
        let cert = cert.filter(|(c, _)| c.exists());
        let cert = cert.as_ref().map(|(a, b)| (a.as_path(), b.as_path()));
        let body = nginx_server_conf(p, sites_root, fpm_port, http_port, https_port, cert)?;
        std::fs::write(sites_dir.join(format!("{p}.conf")), body)?;
        includes.push(format!("{}/{}.conf", sites_dir.display(), p));
    }
    let system_mime = "/etc/nginx/mime.types";
    let mime = std::path::Path::new(system_mime)
        .exists()
        .then_some(system_mime.to_string())
        .or_else(|| {
            let alt = etc.join("nginx/mime.types");
            alt.exists().then(|| alt.display().to_string())
        });
    let conf = generate_nginx_conf(&includes, pid, error_log, mime.as_deref())?;
    std::fs::write(conf_dir.join("nginx.conf"), conf)
        .map_err(|e| Error::Other(format!("write nginx.conf: {e}")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn main_conf_is_foreground_with_includes() {
        let c = generate_nginx_conf(
            &["/etc/nginx/sites/a.conf".to_string()],
            "/run/nginx.pid",
            "/logs/nginx.log",
            Some("/etc/nginx/mime.types"),
        )
        .unwrap();
        assert!(c.contains("daemon off;"), "must stay foreground");
        assert!(c.contains("pid /run/nginx.pid;"));
        assert!(c.contains("include /etc/nginx/mime.types;"));
        assert!(c.contains("include /etc/nginx/sites/a.conf;"));
    }

    #[test]
    fn server_block_has_php_pass_and_optional_tls() {
        let c = nginx_server_conf(
            "blog",
            "/Sites",
            9004,
            8080,
            8443,
            Some((
                std::path::Path::new("/c/blog.crt"),
                std::path::Path::new("/c/blog.key"),
            )),
        )
        .unwrap();
        assert!(c.contains("server_name blog.test;"));
        assert!(c.contains("root /Sites/blog;"));
        assert!(c.contains("fastcgi_pass 127.0.0.1:9004;"));
        assert!(c.contains("SCRIPT_FILENAME $document_root$fastcgi_script_name;"));
        assert!(c.contains("listen 8443 ssl;"));
        assert!(c.contains("ssl_certificate /c/blog.crt;"));

        let plain = nginx_server_conf("blog", "/Sites", 9004, 8080, 8443, None).unwrap();
        assert!(!plain.contains("ssl"), "no cert → no ssl listener");
    }

    #[test]
    fn regenerate_writes_conf_and_includes_and_clears_stale() {
        let t = tempfile::tempdir().unwrap();
        let etc = t.path().join("etc");
        let sites_dir = etc.join("nginx/sites");
        std::fs::create_dir_all(&sites_dir).unwrap();
        std::fs::write(sites_dir.join("old.conf"), "server{}").unwrap();
        regenerate(
            &etc,
            "/run/nginx.pid",
            "/logs/nginx.log",
            "/Sites",
            &["alpha".to_string()],
            9004,
            8080,
            8443,
            None,
        )
        .unwrap();
        let conf = std::fs::read_to_string(etc.join("nginx/nginx.conf")).unwrap();
        assert!(!conf.is_empty());
        assert!(!conf.contains("old.conf"), "stale includes must be cleared");
        assert!(conf.contains("/alpha.conf"));
        assert!(!std::fs::exists(sites_dir.join("old.conf")).unwrap());
    }
}
