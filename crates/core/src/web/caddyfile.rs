use crate::error::{Error, Result};

/// Generate a Caddyfile that serves every folder under `sites_root` at
/// `http://<folder>.test`, routing PHP to the given php-fpm port.
pub fn generate_caddyfile(sites_root: &str, php_fpm_port: u16) -> Result<String> {
    if sites_root.is_empty() {
        return Err(Error::Other("sites root must not be empty".into()));
    }
    Ok(format!(
        r#"# generated by fidim - do not edit
{{
	admin off
}}

# auto virtual hosts: any *.test maps to a folder in {sites_root}
*.test {{
	# handle both http and https (.test TLS via local CA, stage 4 enables strict https)
	tls internal
	root * {sites_root}/{{http.request.host_labels.0}}
	encode zstd gzip
	php_fastcgi 127.0.0.1:{php_fpm_port}
	file_server browse
}}"#
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn serves_sites_folder_on_test_tld() {
        let out = generate_caddyfile("/rootHOME/Sites", 9000).unwrap();
        assert!(
            out.contains("root * /rootHOME/Sites/{http.request.host_labels.0}"),
            "{out}"
        );
        assert!(out.contains("127.0.0.1:9000"));
    }

    #[test]
    fn matches_wildcard_test_tld() {
        let out = generate_caddyfile("/x", 9000).unwrap();
        assert!(out.contains("*.test"));
    }

    #[test]
    fn no_sites_root_is_error() {
        assert!(generate_caddyfile("", 9000).is_err());
    }
}
