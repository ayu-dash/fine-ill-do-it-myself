use crate::error::{Error, Result};

/// Generate a Caddyfile that serves every folder under `sites_root` at
/// `http://<folder>.test`, routing PHP to the given php-fpm port.
pub fn generate_caddyfile(sites_root: &str, php_fpm_port: u16) -> Result<String> {
    generate_caddyfile_ports(sites_root, php_fpm_port, 80, 443)
}

/// Port-aware variant: with default 80/443 the site address `*.test` covers
/// HTTP and HTTPS implicitly; otherwise explicit addresses are emitted so
/// unprivileged ports work without root.
pub fn generate_caddyfile_ports(
    sites_root: &str,
    php_fpm_port: u16,
    http_port: u16,
    https_port: u16,
) -> Result<String> {
    if sites_root.is_empty() {
        return Err(Error::Other("sites root must not be empty".into()));
    }
    let common = format!(
        r#"	root * {sites_root}/{{http.request.host_labels.0}}
	encode zstd gzip
	php_fastcgi 127.0.0.1:{php_fpm_port}
	file_server browse"#
    );
    let sites = if http_port == 80 && https_port == 443 {
        format!("*.test {{\n\ttls internal\n{common}\n}}")
    } else {
        format!(
            "https://*.test:{https_port} {{\n\ttls internal\n{common}\n}}\n\nhttp://*.test:{http_port} {{\n{common}\n}}"
        )
    };
    Ok(format!(
        r#"# generated by fidim - do not edit
{{
	admin off
	auto_https off
	https_port {https_port}
}}

{sites}
"#
    ))
}

/// Explicit project list variant: one site block per folder, escaping dots in
/// folder names (caddy treats `.` as DNS separator).
pub fn generate_caddyfile_for_projects(
    sites_root: &str,
    php_fpm_port: u16,
    projects: &[String],
    http_port: u16,
    https_port: u16,
) -> Result<String> {
    let sites: Vec<crate::site::Site> = projects
        .iter()
        .map(|p| crate::site::Site {
            name: p.clone(),
            docroot: std::path::PathBuf::from(format!("{sites_root}/{p}")),
            proxy: None,
        })
        .collect();
    generate_caddyfile_for_sites(&sites, php_fpm_port, http_port, https_port, &|_| {
        "\ttls internal\n".to_string()
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn expect_minimal(out: &str) {
        assert!(
            out.contains("root * /x/{http.request.host_labels.0}"),
            "{out}"
        );
        assert!(out.contains("php_fastcgi 127.0.0.1:9004"), "{out}");
        assert!(out.contains("admin off"));
    }

    #[test]
    fn serves_sites_folder_on_test_tld() {
        let out = generate_caddyfile("/x", 9004).unwrap();
        expect_minimal(&out);
        assert!(out.contains("*.test {"), "{out}");
    }

    #[test]
    fn matches_wildcard_test_tld() {
        let out = generate_caddyfile("/x", 9004).unwrap();
        assert!(out.contains("*.test"));
    }

    #[test]
    fn no_sites_root_is_error() {
        assert!(generate_caddyfile("", 9000).is_err());
    }

    #[test]
    fn alternate_ports_get_explicit_site_addresses() {
        let out = generate_caddyfile_ports("/x", 9004, 8080, 8443).unwrap();
        assert!(out.contains("http://*.test:8080"), "{out}");
        assert!(out.contains("https://*.test:8443"), "{out}");
        assert!(out.contains("https_port 8443"), "{out}");
    }

    #[test]
    fn default_ports_use_implicit_single_site() {
        let out = generate_caddyfile_ports("/x", 9004, 80, 443).unwrap();
        assert!(out.contains("*.test {"), "{out}");
        assert!(!out.contains(":8080"));
    }
}

#[cfg(test)]
mod perfolder_tests {
    use super::*;

    #[test]
    fn generates_vhost_for_folder_with_test_tld() {
        let out =
            generate_caddyfile_for_projects("/x", 9004, &["blog".to_string()], 80, 443).unwrap();
        assert!(out.contains("root * /x/blog"), "{out}");
        assert!(out.contains("blog.test"), "{out}");
        assert!(out.contains("php_fastcgi 127.0.0.1:9004"), "{out}");
    }

    #[test]
    fn escapes_folder_names_with_dots() {
        let out =
            generate_caddyfile_for_projects("/x", 9004, &["my.site".to_string()], 80, 443).unwrap();
        assert!(out.contains("my\\.site.test"), "{out}");
    }

    #[test]
    fn alternate_ports_in_per_folder_blocks() {
        let out =
            generate_caddyfile_for_projects("/x", 9004, &["blog".into()], 8080, 8443).unwrap();
        assert!(out.contains("blog.test:8080"), "{out}");
        assert!(out.contains("blog.test:8443"), "{out}");
    }

    #[test]
    fn proxy_site_uses_reverse_proxy_instead_of_root() {
        let sites = vec![crate::site::Site {
            name: "app".into(),
            docroot: "/x/app".into(),
            proxy: Some(3000),
        }];

        let out =
            generate_caddyfile_for_sites(&sites, 9004, 8080, 8443, &|_| String::new()).unwrap();

        assert!(out.contains("reverse_proxy 127.0.0.1:3000"), "{out}");
        assert!(!out.contains("root * /x/app"), "{out}");
        assert!(!out.contains("php_fastcgi"), "{out}");
    }

    #[test]
    fn per_folder_blocks_use_each_site_docroot() {
        let sites = vec![
            crate::site::Site {
                name: "blog".into(),
                docroot: "/x/blog".into(),
                proxy: None,
            },
            crate::site::Site {
                name: "shop".into(),
                docroot: "/x/shop/public".into(),
                proxy: None,
            },
        ];

        let out =
            generate_caddyfile_for_sites(&sites, 9004, 8080, 8443, &|_| String::new()).unwrap();

        assert!(out.contains("root * /x/blog"), "{out}");
        assert!(out.contains("root * /x/shop/public"), "{out}");
    }
}

/// One HTTPS + one HTTP block per site, using the detected docroot and a
/// caller-supplied TLS line for the HTTPS block.
pub fn generate_caddyfile_for_sites(
    sites: &[crate::site::Site],
    php_fpm_port: u16,
    http_port: u16,
    https_port: u16,
    tls_line: &dyn Fn(&crate::site::Site) -> String,
) -> crate::error::Result<String> {
    let mut out =
        String::from("# generated by fidim - do not edit\n{\n\tadmin off\n\tauto_https off\n");
    out.push_str(&format!(
        "\thttps_port {https_port}\n\tdefault_sni localhost\n}}\n\n"
    ));
    for site in sites {
        let esc = site.name.replace('.', "\\.");
        let docroot = site.docroot_str();
        let tls = tls_line(site);
        let body = if let Some(port) = site.proxy {
            format!("\treverse_proxy 127.0.0.1:{port}\n")
        } else {
            format!(
                "\troot * {docroot}\n\tphp_fastcgi 127.0.0.1:{php_fpm_port}\n\tfile_server browse\n"
            )
        };
        out.push_str(&format!(
            "https://{esc}.test:{https_port} {{\n{tls}{body}}}\n\n"
        ));
        out.push_str(&format!("http://{esc}.test:{http_port} {{\n{body}}}\n\n"));
    }
    Ok(out)
}

#[cfg(test)]
mod tls_tests {
    use super::*;

    #[test]
    fn tls_line_closure_is_embedded_into_https_block() {
        let sites = vec![crate::site::Site {
            name: "blog".into(),
            docroot: "/x/blog".into(),
            proxy: None,
        }];
        let out = generate_caddyfile_for_sites(&sites, 9004, 8080, 8443, &|s| {
            format!(
                "\ttls /etc/certs/{}.crt /etc/certs/{}.key\n",
                s.name, s.name
            )
        })
        .unwrap();
        let blk = out.split("https://blog.test:8443").nth(1).unwrap();
        assert!(blk.contains("tls /etc/certs/blog.crt /etc/certs/blog.key"));
        assert!(!blk.contains("internal"));
        let http = out.split("http://blog.test:8080").nth(1).unwrap();
        assert!(!http.contains("tls"));
    }
}
