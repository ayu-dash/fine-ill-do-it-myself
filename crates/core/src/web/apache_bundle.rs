//! Install Apache from the pinned Debian packages listed in the manifest.
//!
//! Apache ships no official Linux binary and fidim's generated config loads
//! `modules/mod_*.so` relative to the server root, so `fidim install httpd`
//! assembles a relocatable tree (`libexec/httpd`, `lib/`, `modules/`) from the
//! exact `.deb` files pinned in `default_manifest.toml`. The installer build
//! uses the same recipe, which keeps one source of truth for every checksum.

use std::io::Read;
use std::path::{Path, PathBuf};

use crate::error::{Error, Result};
use crate::installer::{sha256_hex, Fetcher};
use crate::manifest::{BinarySource, Lock, ManifestEntry};
use crate::supervisor::Env;

/// Modules referenced by the generated httpd.conf. Bundling only these keeps
/// the runtime small and avoids optional dependencies (lua, xml, ldap, ...).
const MODULES: [&str; 11] = [
    "mpm_event",
    "authz_core",
    "dir",
    "autoindex",
    "mime",
    "rewrite",
    "proxy",
    "proxy_http",
    "proxy_fcgi",
    "ssl",
    "socache_shmcb",
];

/// Apache-2.0 text; Debian packages only ship a copyright file.
const APACHE_LICENSE: &str = include_str!("apache-LICENSE.txt");

/// The wrapper fidim runs: it adds the private libraries without touching the
/// rest of the system and then execs the real httpd.
pub fn wrapper_script(runtime_root: &Path) -> String {
    format!(
        "#!/bin/sh\n\
         # generated by fidim - runs the bundled Apache with its private libraries\n\
         LD_LIBRARY_PATH=\"{root}/lib${{LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}}\"\n\
         export LD_LIBRARY_PATH\n\
         exec \"{root}/libexec/httpd\" \"$@\"\n",
        root = runtime_root.display()
    )
}

/// Download every pinned package, verify it, and install the runtime.
/// Returns the path of the generated `bin/httpd/httpd` wrapper.
pub fn install<F: Fetcher>(
    env: &Env,
    src: &BinarySource,
    lock: &mut Lock,
    fetcher: &F,
) -> Result<PathBuf> {
    if src.debs.is_empty() {
        return Err(Error::Other(format!(
            "{} has no Debian package recipe in the manifest",
            src.name
        )));
    }
    let runtime_parent = env.paths.runtimes().join("httpd");
    let runtime_root = runtime_parent.join(&src.version);
    let staging = runtime_parent.join(format!(".{}-staging", src.version));
    let _ = std::fs::remove_dir_all(&staging);
    for sub in ["lib", "libexec", "modules"] {
        std::fs::create_dir_all(staging.join(sub))?;
    }

    for deb in &src.debs {
        if deb.sha256.len() != 64 || !deb.sha256.chars().all(|c| c.is_ascii_hexdigit()) {
            return Err(Error::Other(format!(
                "{} package {} must pin a sha256",
                src.name, deb.url
            )));
        }
        let bytes = fetcher.fetch(&deb.url)?;
        if sha256_hex(&bytes) != deb.sha256 {
            return Err(Error::ChecksumMismatch(src.name.clone()));
        }
        extract_deb(&bytes, &staging)?;
    }

    let httpd = staging.join("libexec/httpd");
    if !httpd.is_file() {
        let _ = std::fs::remove_dir_all(&staging);
        return Err(Error::Other(
            "the pinned packages contain no usr/sbin/apache2".into(),
        ));
    }
    make_executable(&httpd)?;
    std::fs::write(staging.join("LICENSE"), APACHE_LICENSE)?;

    if runtime_root.exists() {
        std::fs::remove_dir_all(&runtime_root)?;
    }
    std::fs::rename(&staging, &runtime_root)?;

    // fidim derives ServerRoot from the modules/ dir next to bin/httpd/httpd,
    // so expose the modules in the data root, next to bin/.
    let modules_dir = env.paths.root().join("modules");
    std::fs::create_dir_all(&modules_dir)?;
    for module in MODULES {
        let file = format!("mod_{module}.so");
        let from = runtime_root.join("modules").join(&file);
        if !from.is_file() {
            return Err(Error::Other(format!(
                "{} is missing from the packages",
                file
            )));
        }
        std::fs::copy(&from, modules_dir.join(&file))?;
    }

    let bin_dir = env.paths.bin().join("httpd");
    std::fs::create_dir_all(&bin_dir)?;
    let wrapper = bin_dir.join("httpd");
    std::fs::write(&wrapper, wrapper_script(&runtime_root))?;
    make_executable(&wrapper)?;

    let licenses = env.paths.root().join("licenses");
    std::fs::create_dir_all(&licenses)?;
    std::fs::write(licenses.join("apache-2.0.txt"), APACHE_LICENSE)?;

    // The lock records the recipe (all package checksums) instead of one URL.
    let recipe = src
        .debs
        .iter()
        .map(|deb| deb.sha256.as_str())
        .collect::<Vec<_>>()
        .join(",");
    lock.binaries.insert(
        src.name.clone(),
        ManifestEntry {
            url: format!("deb-recipe:{}", src.version),
            sha256: sha256_hex(recipe.as_bytes()),
            installed_at: String::new(),
        },
    );
    lock.save(&env.lock_path())?;

    Ok(wrapper)
}

struct ArMember<'a> {
    name: String,
    data: &'a [u8],
}

/// Minimal `ar` reader: `.deb` files are a flat ar archive of
/// `debian-binary`, `control.tar.*` and `data.tar.*`.
fn ar_members(bytes: &[u8]) -> Result<Vec<ArMember<'_>>> {
    if !bytes.starts_with(b"!<arch>\n") {
        return Err(Error::Other("not a .deb (missing ar magic)".into()));
    }
    let mut members = Vec::new();
    let mut pos = 8;
    while pos + 60 <= bytes.len() {
        let header = &bytes[pos..pos + 60];
        if &header[58..60] != b"`\n" {
            return Err(Error::Other("corrupt ar member header".into()));
        }
        let name = std::str::from_utf8(&header[0..16])
            .map_err(|_| Error::Other("non-UTF-8 ar member name".into()))?
            .trim()
            .trim_end_matches('/')
            .to_string();
        let size: usize = std::str::from_utf8(&header[48..58])
            .map_err(|_| Error::Other("non-UTF-8 ar member size".into()))?
            .trim()
            .parse()
            .map_err(|_| Error::Other("invalid ar member size".into()))?;
        let start = pos + 60;
        let end = start
            .checked_add(size)
            .ok_or_else(|| Error::Other("ar member size overflow".into()))?;
        if end > bytes.len() {
            return Err(Error::Other("truncated ar member".into()));
        }
        members.push(ArMember {
            name,
            data: &bytes[start..end],
        });
        pos = end + (size % 2);
    }
    Ok(members)
}

fn extract_deb(bytes: &[u8], staging: &Path) -> Result<()> {
    let members = ar_members(bytes)?;
    let data = members
        .iter()
        .find(|m| m.name.starts_with("data.tar"))
        .ok_or_else(|| Error::Other("deb has no data.tar member".into()))?;
    let reader: Box<dyn Read> = if data.name.ends_with(".xz") {
        Box::new(xz2::read::XzDecoder::new(data.data))
    } else if data.name.ends_with(".gz") {
        Box::new(flate2::read::GzDecoder::new(data.data))
    } else {
        return Err(Error::Other(format!(
            "unsupported .deb compression: {}",
            data.name
        )));
    };
    let mut archive = tar::Archive::new(reader);
    for entry in archive.entries()? {
        let mut entry = entry?;
        let path = entry.path()?.into_owned();
        let Some(target) = deb_target(&path) else {
            continue;
        };
        let out = staging.join(&target);
        if let Some(parent) = out.parent() {
            std::fs::create_dir_all(parent)?;
        }
        if entry.header().entry_type() == tar::EntryType::Symlink {
            #[cfg(unix)]
            if let Some(link) = entry.link_name()? {
                let _ = std::fs::remove_file(&out);
                std::os::unix::fs::symlink(&link, &out)?;
            }
        } else {
            entry.unpack(&out)?;
        }
    }
    Ok(())
}

/// Which files of a Debian package belong in the runtime tree.
fn deb_target(path: &Path) -> Option<PathBuf> {
    let raw = path.to_string_lossy();
    // Debian data.tar members are stored as `./usr/...`.
    let full = raw.strip_prefix("./").unwrap_or(raw.as_ref());
    let name = path.file_name()?.to_string_lossy().to_string();
    if full == "usr/sbin/apache2" {
        return Some(PathBuf::from("libexec/httpd"));
    }
    let module = name
        .strip_prefix("mod_")
        .and_then(|rest| rest.strip_suffix(".so"));
    if full.starts_with("usr/lib/apache2/modules/") && module.is_some_and(|m| MODULES.contains(&m))
    {
        return Some(Path::new("modules").join(&name));
    }
    if (full.starts_with("usr/lib/x86_64-linux-gnu/") || full.starts_with("lib/x86_64-linux-gnu/"))
        && name.contains(".so")
    {
        return Some(Path::new("lib").join(&name));
    }
    None
}

fn make_executable(path: &Path) -> Result<()> {
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perm = std::fs::metadata(path)?.permissions();
        perm.set_mode(0o755);
        std::fs::set_permissions(path, perm)?;
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::manifest::BinarySource;
    use std::collections::HashMap;
    use std::io::Write;

    #[derive(Default)]
    struct MapFetcher(HashMap<String, Vec<u8>>);

    impl Fetcher for MapFetcher {
        fn fetch(&self, url: &str) -> Result<Vec<u8>> {
            self.0
                .get(url)
                .cloned()
                .ok_or_else(|| Error::Other(format!("unexpected fetch: {url}")))
        }
    }

    fn env() -> (Env, tempfile::TempDir) {
        let t = tempfile::tempdir().unwrap();
        let env = Env::new(t.path().join("app"), t.path().join("projects"));
        env.ensure_dirs().unwrap();
        (env, t)
    }

    fn deb_bytes(data_tar: &[u8]) -> Vec<u8> {
        let mut out = b"!<arch>\n".to_vec();
        let members: [(&str, &[u8]); 3] = [
            ("debian-binary", b"2.0\n"),
            ("control.tar.xz", b""),
            ("data.tar.xz", data_tar),
        ];
        for (name, data) in members {
            let mut header = [b' '; 60];
            header[..name.len()].copy_from_slice(name.as_bytes());
            let size = format!("{:<10}", data.len());
            header[48..58].copy_from_slice(size.as_bytes());
            header[58] = b'`';
            header[59] = b'\n';
            out.extend_from_slice(&header);
            out.extend_from_slice(data);
            if data.len() % 2 == 1 {
                out.push(b'\n');
            }
        }
        out
    }

    fn data_tar_xz() -> Vec<u8> {
        let mut tar_bytes = Vec::new();
        {
            let mut builder = tar::Builder::new(&mut tar_bytes);
            let mut files: Vec<(String, &[u8])> = vec![
                (
                    "usr/sbin/apache2".to_string(),
                    b"#!/bin/sh\nexit 0\n".as_slice(),
                ),
                (
                    "usr/lib/x86_64-linux-gnu/libapr-1.so.0.7.2".to_string(),
                    b"lib".as_slice(),
                ),
            ];
            for module in MODULES {
                files.push((
                    format!("usr/lib/apache2/modules/mod_{module}.so"),
                    b"module".as_slice(),
                ));
            }
            for (path, data) in &files {
                let mut header = tar::Header::new_gnu();
                header.set_size(data.len() as u64);
                header.set_mode(0o644);
                header.set_entry_type(tar::EntryType::Regular);
                builder.append_data(&mut header, path, *data).unwrap();
            }
            let mut link = tar::Header::new_gnu();
            link.set_size(0);
            link.set_mode(0o777);
            link.set_entry_type(tar::EntryType::Symlink);
            builder
                .append_link(
                    &mut link,
                    "usr/lib/x86_64-linux-gnu/libapr-1.so.0",
                    "libapr-1.so.0.7.2",
                )
                .unwrap();
            builder.finish().unwrap();
        }
        let mut encoder = xz2::write::XzEncoder::new(Vec::new(), 6);
        encoder.write_all(&tar_bytes).unwrap();
        encoder.finish().unwrap()
    }

    fn source(sha: &str) -> BinarySource {
        let toml = format!(
            r#"
name = "httpd"
version = "2.4.67"
url = ""
debs = [{{ url = "https://example.test/apache2-bin.deb", sha256 = "{sha}" }}]
"#
        );
        toml::from_str(&toml).unwrap()
    }

    #[test]
    fn installs_a_runnable_tree_from_the_pinned_packages() {
        let (env, _t) = env();
        let deb = deb_bytes(&data_tar_xz());
        let sha = sha256_hex(&deb);
        let mut fetcher = MapFetcher::default();
        fetcher
            .0
            .insert("https://example.test/apache2-bin.deb".into(), deb.clone());
        let mut lock = Lock::default();
        let src = source(&sha);

        let wrapper = install(&env, &src, &mut lock, &fetcher).unwrap();

        assert_eq!(wrapper, env.paths.bin().join("httpd/httpd"));
        assert!(wrapper.is_file());
        let runtime = env.paths.runtimes().join("httpd/2.4.67");
        assert!(runtime.join("libexec/httpd").is_file());
        assert!(runtime.join("LICENSE").is_file());
        assert!(
            runtime.join("lib/libapr-1.so.0").is_symlink(),
            "the soname symlink must survive extraction"
        );
        assert_eq!(
            std::fs::read_link(runtime.join("lib/libapr-1.so.0")).unwrap(),
            Path::new("libapr-1.so.0.7.2")
        );
        assert!(env.paths.root().join("modules/mod_mpm_event.so").is_file());
        assert!(env.paths.root().join("licenses/apache-2.0.txt").is_file());
        let body = std::fs::read_to_string(&wrapper).unwrap();
        assert!(
            body.contains("runtimes/httpd/2.4.67/libexec/httpd"),
            "{body}"
        );
        assert!(body.contains("LD_LIBRARY_PATH"), "{body}");
        assert_eq!(
            lock.binaries.get("httpd").map(|e| e.url.as_str()),
            Some("deb-recipe:2.4.67")
        );
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            let mode = std::fs::metadata(&wrapper).unwrap().permissions().mode();
            assert!(mode & 0o111 != 0, "wrapper must be executable: {mode:o}");
        }
    }

    #[test]
    fn rejects_a_package_that_does_not_match_its_checksum() {
        let (env, _t) = env();
        let deb = deb_bytes(&data_tar_xz());
        let mut fetcher = MapFetcher::default();
        fetcher
            .0
            .insert("https://example.test/apache2-bin.deb".into(), deb);
        let mut lock = Lock::default();
        let src = source(&"0".repeat(64));

        let err = install(&env, &src, &mut lock, &fetcher).unwrap_err();

        assert!(matches!(err, Error::ChecksumMismatch(_)), "{err}");
        assert!(!env.paths.runtimes().join("httpd/2.4.67").exists());
    }

    #[test]
    fn rejects_a_deb_without_data_member() {
        let (env, _t) = env();
        let mut broken = b"!<arch>\n".to_vec();
        let data = b"";
        let mut header = [b' '; 60];
        header[..11].copy_from_slice(b"debian-biny");
        header[48..58].copy_from_slice(format!("{:<10}", data.len()).as_bytes());
        header[58] = b'`';
        header[59] = b'\n';
        broken.extend_from_slice(&header);
        let sha = sha256_hex(&broken);
        let mut fetcher = MapFetcher::default();
        fetcher
            .0
            .insert("https://example.test/apache2-bin.deb".into(), broken);
        let mut lock = Lock::default();

        let err = install(&env, &source(&sha), &mut lock, &fetcher).unwrap_err();

        assert!(err.to_string().contains("data.tar"), "{err}");
    }
}
