#!/bin/sh
set -eu

repo_root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
test_root=$(mktemp -d)
cleanup() {
    rm -rf -- "$test_root"
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM

make_fake_fidim() {
    version=$1
    destination=$2
    cat > "$destination" <<EOF
#!/bin/sh
if [ "\${1:-}" = "--version" ]; then
    printf 'fidim %s\\n' '$version'
else
    printf 'fake fidim %s\\n' '$version'
fi
EOF
    chmod 755 "$destination"
}

fake_binary=$test_root/fidim
installer=$test_root/fine-ill-do-it-myself-test.run
home=$test_root/home
mkdir -p "$home"

make_fake_fidim 1.0 "$fake_binary"

"$repo_root/scripts/build-run-installer.sh" "$fake_binary" "$installer"

help=$(HOME=$home "$installer" --help)
printf '%s\n' "$help" | grep -F "$home/.local/share/fine-ill-do-it-myself" >/dev/null
printf '%s\n' "$help" | grep -F "$home/.local/bin/fidim" >/dev/null
HOME=$home "$installer" --yes --data-dir "$home/.local/share/fine-ill-do-it-myself" --bin-dir "$home/.local/bin"
test "$("$home/.local/bin/fidim" --version)" = "fidim 1.0"
test -x "$home/.local/share/fine-ill-do-it-myself/fidim"
test "$(readlink "$home/.local/bin/fidim")" = "$home/.local/share/fine-ill-do-it-myself/fidim"
test -x "$home/.local/share/fine-ill-do-it-myself/uninstall.sh"

# The installer ships no bundled components; only fidim and uninstall.sh.
test ! -e "$home/.local/share/fine-ill-do-it-myself/runtimes/phpmyadmin"
test ! -e "$home/.local/share/fine-ill-do-it-myself/bin/composer"
test ! -e "$home/.local/share/fine-ill-do-it-myself/bin/php"
test ! -e "$home/.local/share/fine-ill-do-it-myself/licenses/php-3.01.txt"

# Re-running the installer must not overwrite an existing fidim without confirmation.
printf 'keep this\n' > "$home/.local/share/fine-ill-do-it-myself/fidim"

make_fake_fidim 2.0 "$fake_binary"
"$repo_root/scripts/build-run-installer.sh" "$fake_binary" "$installer"
if HOME=$home "$installer" --data-dir "$home/.local/share/fine-ill-do-it-myself" --bin-dir "$home/.local/bin" </dev/null; then
    printf 'error: installer replaced an existing link without confirmation\n' >&2
    exit 1
fi
test "$("$home/.local/bin/fidim" --version)" = "fidim 1.0"

HOME=$home "$installer" --yes --data-dir "$home/.local/share/fine-ill-do-it-myself" --bin-dir "$home/.local/bin"
test "$("$home/.local/bin/fidim" --version)" = "fidim 2.0"

data_root=$home/.local/share/fine-ill-do-it-myself
mkdir -p "$data_root/projects/sample" "$data_root/runtimes/php"
printf 'keep project data\n' > "$data_root/projects/sample/index.php"
printf 'keep runtime data\n' > "$data_root/runtimes/php/version"
for shim in \
    mysql mariadb mysqladmin mariadb-admin mysqldump mariadb-dump \
    php composer node npm npx corepack python python3 pip pip3 go gofmt \
    java javac jar
do
    printf '#!/bin/sh\n# generated by fidim; managed shim\n' > "$home/.local/bin/$shim"
    chmod 755 "$home/.local/bin/$shim"
done
printf '#!/bin/sh\n# user-owned command\n' > "$home/.local/bin/npm"
chmod 755 "$home/.local/bin/npm"
"$data_root/uninstall.sh" \
    --data-dir "$data_root" \
    --bin-dir "$home/.local/bin" \
    --shim-dir "$home/.local/bin"
test ! -e "$home/.local/bin/fidim"
for shim in \
    mysql mariadb mysqladmin mariadb-admin mysqldump mariadb-dump \
    php composer node npx corepack python python3 pip pip3 go gofmt \
    java javac jar
do
    test ! -e "$home/.local/bin/$shim"
done
test -x "$home/.local/bin/npm"
test ! -e "$data_root/fidim"
test ! -e "$data_root/uninstall.sh"
test -f "$data_root/projects/sample/index.php"
test -f "$data_root/runtimes/php/version"

make_fake_fidim 3.0 "$fake_binary"
"$repo_root/scripts/build-run-installer.sh" "$fake_binary" "$installer"
HOME=$home "$installer" --yes --data-dir "$data_root" --bin-dir "$home/.local/bin"
mkdir "$test_root/link-target"
rm -f "$home/.local/bin/fidim"
ln -s "$test_root/link-target" "$home/.local/bin/fidim"
"$data_root/uninstall.sh" --data-dir "$data_root" --bin-dir "$home/.local/bin"
test "$(readlink "$home/.local/bin/fidim")" = "$test_root/link-target"
test -z "$(find "$test_root/link-target" -mindepth 1 -print -quit)"

default_home=$test_root/default-home
mkdir -p "$default_home"
HOME=$default_home "$installer" --yes
test "$("$default_home/.local/bin/fidim" --version)" = "fidim 3.0"
test -x "$default_home/.local/share/fine-ill-do-it-myself/fidim"

xdg_home=$test_root/xdg-home
mkdir -p "$xdg_home"
HOME=$xdg_home XDG_DATA_HOME=$test_root/xdg-data "$installer" --yes
test "$("$xdg_home/.local/bin/fidim" --version)" = "fidim 3.0"
test -x "$test_root/xdg-data/fine-ill-do-it-myself/fidim"

printf 'Installer tests passed.\n'