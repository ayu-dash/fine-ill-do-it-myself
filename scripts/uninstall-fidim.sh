#!/bin/sh
set -eu

usage() {
    printf '%s\n' \
        'Uninstall the fidim executable for the current user.' \
        '' \
        'Usage: uninstall.sh [--data-dir DIR] [--bin-dir DIR] [--shim-dir DIR]' \
        '' \
        'This removes the installed executable, its uninstaller, and the matching' \
        'fidim command symlink. Projects and the MariaDB data directory are kept.' \
        '' \
        'Options:' \
        '  --data-dir DIR  Installed fidim data root (overrides XDG default)' \
        '  --bin-dir DIR   Directory containing the fidim command symlink' \
        '  --shim-dir DIR  Directory containing wrappers created by fidim env --install' \
        '  -h, --help      Show this help'
}

if [ -z "${HOME:-}" ]; then
    printf 'error: HOME is not set\n' >&2
    exit 1
fi

data_home=${XDG_DATA_HOME:-"$HOME/.local/share"}
data_root=$data_home/fine-ill-do-it-myself
bin_dir=$HOME/.local/bin
shim_dir=${FIDIM_SHIM_DIR:-"$HOME/.local/bin"}

while [ "$#" -gt 0 ]; do
    case "$1" in
        --data-dir)
            [ "$#" -ge 2 ] || { printf 'error: --data-dir requires a path\n' >&2; exit 2; }
            data_root=$2
            shift 2
            ;;
        --bin-dir)
            [ "$#" -ge 2 ] || { printf 'error: --bin-dir requires a path\n' >&2; exit 2; }
            bin_dir=$2
            shift 2
            ;;
        --shim-dir)
            [ "$#" -ge 2 ] || { printf 'error: --shim-dir requires a path\n' >&2; exit 2; }
            shim_dir=$2
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            printf 'error: unknown option: %s\n' "$1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

case "$data_root:$bin_dir:$shim_dir" in
    /*:/*:/*) ;;
    *)
        printf 'error: install paths must be absolute\n' >&2
        exit 1
        ;;
esac

if [ "$data_root" = "/" ]; then
    printf 'error: refusing to uninstall from filesystem root\n' >&2
    exit 1
fi

binary=$data_root/fidim
uninstaller=$data_root/uninstall.sh
link=$bin_dir/fidim

for shim in \
    mysql mariadb mysqladmin mariadb-admin mysqldump mariadb-dump \
    php composer \
    node npm npx corepack \
    python python3 pip pip3 \
    go gofmt \
    java javac jar
do
    shim_path=$shim_dir/$shim
    if [ -f "$shim_path" ] && [ ! -L "$shim_path" ]; then
        marker=$(sed -n '2p' "$shim_path")
        case "$marker" in
            '# generated by fidim;'*)
                rm -f -- "$shim_path"
                printf 'Removed fidim shim %s\n' "$shim_path"
                ;;
        esac
    fi
done

if [ -L "$link" ]; then
    target=$(readlink "$link")
    if [ "$target" = "$binary" ]; then
        rm -f -- "$link"
        printf 'Removed command link %s\n' "$link"
    else
        printf 'Keeping unrelated symlink %s -> %s\n' "$link" "$target"
    fi
elif [ -e "$link" ]; then
    printf 'Keeping non-symlink command path %s\n' "$link"
fi

if [ -f "$binary" ] && [ ! -L "$binary" ]; then
    rm -f -- "$binary"
    printf 'Removed executable %s\n' "$binary"
elif [ -e "$binary" ] || [ -L "$binary" ]; then
    printf 'Keeping non-regular executable path %s\n' "$binary"
fi
if [ -f "$uninstaller" ] && [ ! -L "$uninstaller" ]; then
    rm -f -- "$uninstaller"
    printf 'Removed uninstaller %s\n' "$uninstaller"
elif [ -e "$uninstaller" ] || [ -L "$uninstaller" ]; then
    printf 'Keeping non-regular uninstaller path %s\n' "$uninstaller"
fi

if [ -d "$data_root/data" ]; then
    find "$data_root/data" -mindepth 1 -maxdepth 1 ! -name mariadb -exec rm -rf -- {} +
fi
find "$data_root" -mindepth 1 -maxdepth 1 \
    ! -name projects \
    ! -name data \
    -exec rm -rf -- {} +

printf 'Kept projects and MariaDB data in %s.\n' "$data_root"
